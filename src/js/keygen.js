  function randomBytes(n) {
    var arr = new Uint8Array(n);
    crypto.getRandomValues(arr);
    return arr;
  }

  function randomFromCharset(charset, length) {
    var result = "";
    var charsetLength = charset.length;

    // Use rejection sampling to avoid modulo bias when mapping bytes to charset indices.
    while (result.length < length) {
      // Generate enough bytes to potentially fill the remaining length.
      var bytes = randomBytes(length - result.length);
      for (var i = 0; i < bytes.length && result.length < length; i++) {
        var idx = bytes[i];
        if (idx < charsetLength) {
          result += charset[idx];
        }
      }
    }
    return result;
  }

  function randomHex(bytes) {
    var arr = randomBytes(bytes);
    var result = "";
    for (var i = 0; i < arr.length; i++) {
      result += ("0" + arr[i].toString(16)).slice(-2);
    }
    return result;
  }

  function randomBase64(bytes) {
    var arr = randomBytes(bytes);
    var binary = "";
    for (var i = 0; i < arr.length; i++) {
      binary += String.fromCharCode(arr[i]);
    }
    return btoa(binary);
  }

