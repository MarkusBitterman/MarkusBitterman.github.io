    var hex = "";
    for (var i = 0; i < 16; i++) {
      hex += ("0" + bytes[i].toString(16)).slice(-2);
    }
    return (
      hex.slice(0, 8) +
      "-" +
      hex.slice(8, 12) +
      "-" +
      hex.slice(12, 16) +
      "-" +
      hex.slice(16, 20) +
      "-" +
      hex.slice(20, 32)
    );
