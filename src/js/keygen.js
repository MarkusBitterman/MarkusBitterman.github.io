  // --- Rendering ---
  function generateAll() {
    var container = document.getElementById("keygen-output");
    if (!container) return;
    container.innerHTML = "";

    var order = [
      "memorable",
      "pin",
      "strong16",
      "fort32",
      "alphanum24",
      "hex128",
      "hex256",
      "base64",
      "uuid",
      "api",
    ];
    for (var k = 0; k < order.length; k++) {
      var key = order[k];
      var gen = GENERATORS[key];
      var section = document.createElement("div");
      section.className = "box mb-4";

      var heading = document.createElement("h4");
      heading.className = "title is-5 mb-3";
      heading.textContent = gen.label;
      section.appendChild(heading);

      for (var i = 0; i < gen.count; i++) {
        var value = gen.fn();
        var row = document.createElement("div");
        row.className = "field has-addons mb-2";

        var inputControl = document.createElement("div");
        inputControl.className = "control is-expanded";
        var input = document.createElement("input");
        input.className = "input is-family-monospace is-small";
        input.type = "text";
        input.readOnly = true;
        input.value = value;
        inputControl.appendChild(input);
        row.appendChild(inputControl);

        var btnControl = document.createElement("div");
        btnControl.className = "control";
        var btn = document.createElement("button");
        btn.className = "button is-info is-small";
        btn.innerHTML = '<span class="icon"><i class="fas fa-copy"></i></span>';
        btn.title = "Copy to clipboard";
        btn.setAttribute("data-value", value);
        btn.addEventListener("click", copyHandler);
        btnControl.appendChild(btn);
        row.appendChild(btnControl);

        section.appendChild(row);
      }
      container.appendChild(section);
    }
  }

  function copyHandler(e) {
    var btn = e.currentTarget;
    var value = btn.getAttribute("data-value");
    navigator.clipboard.writeText(value).then(function () {
      btn.innerHTML = '<span class="icon"><i class="fas fa-check"></i></span>';
      btn.classList.remove("is-info");
      btn.classList.add("is-success");
      setTimeout(function () {
        btn.innerHTML = '<span class="icon"><i class="fas fa-copy"></i></span>';
        btn.classList.remove("is-success");
        btn.classList.add("is-info");
      }, 1500);
    });
  }

