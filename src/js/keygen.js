  function passphrase(wordCount, separator) {
    wordCount = wordCount || 4;
    separator = separator || "-";
    var bytes = randomBytes(wordCount * 2); // 2 bytes per word for better distribution
    var words = [];
    for (var i = 0; i < wordCount; i++) {
      var index = ((bytes[i * 2] << 8) | bytes[i * 2 + 1]) % WORDS.length;
      words.push(WORDS[index]);
    }
    return words.join(separator);
  }

